export function adminCopy(locale: Locale): AdminCopy {
  return localizedCatalog(locale, "admin", { en: english, "zh-HK": cantonese, "ja-JP": japanese });
}

/** A readable name for a refusal scope; unknown scopes show as they are. */
export function refusalScopeLabel(copy: AdminCopy, scope: string): string {
  if (scope.startsWith("ai-key-check")) return copy.scope_ai_key_check;
  if (scope === "join-preview" || scope === "claim-preview") return copy.scope_invitation;
  if (scope === "google-start") return copy.scope_google_callback;
  const key = `scope_${scope.replace(/-/gu, "_")}` as keyof AdminCopy;
  return key in copy ? copy[key] : scope;
}
