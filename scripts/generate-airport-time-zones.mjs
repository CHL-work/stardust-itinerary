// Regenerate the tiny browser-safe IATA/zone catalog, not the full airport database.
// Run: node scripts/generate-airport-time-zones.mjs [--check]
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const revision = "a89e4e0dda9d9878337e2da190ebe1ef1d6af705";
const base = `https://raw.githubusercontent.com/mwgg/Airports/${revision}/`;
const expected = {
  "airports.json": "a7754cbe722ea21f0f9ab1ef07f4f07ee1e85b9cc99191ebde0b49fabb3c149a",
  LICENSE: "685b4a7b0fbac021cf4c56513ee5c7532c7cd174177e94c3350a92b504f929a3",
};
async function source(name) {
  const response = await fetch(`${base}${name}`, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`Airport source failed: ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (createHash("sha256").update(bytes).digest("hex") !== expected[name]) throw new Error("Airport source checksum mismatch");
  return bytes.toString("utf8");
}
const [raw, license] = await Promise.all([source("airports.json"), source("LICENSE")]);
const candidates = new Map();
for (const row of Object.values(JSON.parse(raw))) {
  if (!/^[A-Z]{3}$/.test(row.iata ?? "") || !/^[A-Za-z]+(?:\/[A-Za-z0-9_+\-]+){1,2}$/.test(row.tz ?? "")) continue;
  const zones = candidates.get(row.iata) ?? new Set();
  zones.add(row.tz);
  candidates.set(row.iata, zones);
}
const grouped = new Map();
let count = 0;
for (const [code, zones] of [...candidates].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  // A reused/ambiguous code is not a safe time-zone hint.
  if (zones.size !== 1) continue;
  const zone = [...zones][0];
  const codes = grouped.get(zone) ?? [];
  codes.push(code);
  grouped.set(zone, codes);
  count += 1;
}
const groups = Object.fromEntries([...grouped].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([zone, codes]) => [zone, codes.join(" ")]));
const generated = `// Generated by scripts/generate-airport-time-zones.mjs. Do not edit.\n// mwgg/Airports ${revision}; MIT, see airport-time-zones.LICENSE.\n// ${count} unambiguous IATA codes; names, coordinates and other source fields are omitted.\nexport const airportTimeZoneGroups: Readonly<Record<string, string>> = ${JSON.stringify(groups, null, 2)};\n`;
if (Buffer.byteLength(generated) > 50_000) throw new Error("Airport catalog exceeds the browser-size budget");
for (const [name, value] of [["airport-time-zones.generated.ts", generated], ["airport-time-zones.LICENSE", `${license.trimEnd()}\n`]]) {
  const path = new URL(`../src/lib/app/${name}`, import.meta.url);
  if (process.argv.includes("--check")) {
    // Git may check out CRLF on Windows; content reproducibility is independent of line endings.
    if ((await readFile(path, "utf8")).replace(/\r\n/gu, "\n") !== value.replace(/\r\n/gu, "\n")) throw new Error(`Generated ${name} differs`);
  } else await writeFile(path, value);
}
console.log(`Airport zones: ${count} codes, ${grouped.size} zones, ${Buffer.byteLength(generated)} bytes; ${process.argv.includes("--check") ? "verified" : "generated"}.`);
