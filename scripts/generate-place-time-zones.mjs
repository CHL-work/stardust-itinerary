// Generate only locality names and zones, not a general geocoder or venue database.
// Download cities15000.zip from https://download.geonames.org/export/dump/ and extract it.
// Run: node scripts/generate-place-time-zones.mjs <cities15000.txt> [--check]
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";

const sourcePath = process.argv[2];
if (!sourcePath || sourcePath.startsWith("--")) throw new Error("Provide the reviewed GeoNames cities15000.txt snapshot");
const raw = await readFile(sourcePath);
const checksum = "18fbcbbe63fac5ae12c411e92b1bcb37281f2afed2e2b6a42beffe75fbbf812e";
if (createHash("sha256").update(raw).digest("hex") !== checksum) throw new Error("GeoNames snapshot changed; review the data before updating its checksum");
const normalize = value => value.normalize("NFKC").toLowerCase().replace(/\p{M}/gu, "").replace(/[^\p{L}\p{N}]+/gu, " ").trim();
const groups = new Map();
let count = 0;
const records = [];
const includedNames = new Set();
for (const line of raw.toString("utf8").trim().split(/\r?\n/u)) {
  const fields = line.split("\t");
  const [name, ascii] = [fields[1], fields[2]];
  const [country, admin, zone] = [fields[8], fields[10], fields[17]];
  if (!zone || !/^[A-Z]{2}$/u.test(country)) continue;
  const aliases = fields[3].split(",");
  const shortCityNames = [name, ascii].filter(value => / City$/u.test(value)).map(value => value.slice(0, -5)).filter(value => aliases.includes(value));
  const names = [...new Set([name, ascii, ...shortCityNames, ...aliases
    .filter(value => /^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}ー・＝\s-]{2,30}$/u.test(value)).slice(0, 3)].map(normalize))]
    .filter(value => (value.length >= 3 || /^[\p{Script=Han}]{2}$/u.test(value)) && value.length <= 65);
  records.push({ country, admin, zone, names });
  // The browser keeps major cities/capitals; all namesakes still participate below so a small
  // city's conflicting zone is never silently assigned the larger city's zone.
  if (Number(fields[14]) >= 50_000 || fields[7] === "PPLC") for (const value of names) includedNames.add(value);
}
for (const { country, admin, zone, names } of records) {
  const included = names.filter(value => includedNames.has(value));
  if (!included.length) continue;
  const key = `${zone}|${country}|${country === "US" ? admin : ""}`;
  const values = groups.get(key) ?? new Set();
  for (const value of included) values.add(value);
  groups.set(key, values);
  count++;
}
const rows = [...groups].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
  .map(([key, names]) => [...key.split("|"), [...names].sort().join("|")]);
const generated = `// Generated by scripts/generate-place-time-zones.mjs; do not edit.\n// GeoNames cities15000, 2026-11-08; CC BY 4.0, see place-time-zones.LICENSE.\n// SHA-256 ${checksum}; ${count} localities. Only locality/region names and zones retained.\nexport const placeTimeZoneGroups: readonly (readonly [string, string, string, string])[] = ${JSON.stringify(rows)};\n`;
const compressed = gzipSync(generated).length;
if (compressed > 180_000) throw new Error(`Locality catalog exceeds compressed size budget: ${compressed}`);
const target = new URL("../src/lib/app/place-time-zones.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")).replace(/\r\n/gu, "\n") !== generated) throw new Error("Generated locality catalog differs");
} else await writeFile(target, generated);
console.log(JSON.stringify({ localities: count, groups: groups.size, bytes: Buffer.byteLength(generated), gzipBytes: compressed }));
